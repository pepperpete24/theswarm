export function seedJobs(): Job[] {
  return seeds.map(({ receipt, ...j }) => ({
    ...j,
    manifest: buildManifest({
      jobId: j.id,
      role: j.role,
      member: j.agentId ? m(j.agentId) : undefined,
      tokens: receipt?.tokens,
      cost: receipt?.cost,
      started: receipt?.started,
      finished: receipt?.finished,
      toolCalls: receipt?.calls,
    }),
  }));
}

